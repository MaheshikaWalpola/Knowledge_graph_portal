def search_terms_in_graph(
    term: str,
    graph_iri: str,
    limit: int = 15,
) -> List[Dict]:
    """
    Search for classes/properties by local name or label within a specific graph.
    Namespace-agnostic — works for any uploaded ontology.
    """
    t = (term or "").strip().lower()
    if not t:
        return []

    q = f"""
    SELECT DISTINCT ?s (SAMPLE(?lbl) AS ?lbl) WHERE {{
      GRAPH <{graph_iri}> {{
        ?s ?p ?o .
        FILTER(isIRI(?s))
        OPTIONAL {{ ?s <http://www.w3.org/2000/01/rdf-schema#label> ?lbl }}
        BIND(LCASE(REPLACE(STR(?s), "^.*/|^.*#", "")) AS ?local)
        FILTER(
          CONTAINS(?local, "{t}")
          || (BOUND(?lbl) && CONTAINS(LCASE(STR(?lbl)), "{t}"))
        )
      }}
    }}
    GROUP BY ?s
    LIMIT {limit}
    """
    res = _exec_select(q)
    out = []
    for b in res["results"]["bindings"]:
        out.append({"iri": b["s"]["value"], "label": b.get("lbl", {}).get("value")})
    return out


def resolve_term_in_graph(term: str, graph_iri: str) -> Optional[str]:
    """
    Resolve a term to an IRI within a specific uploaded graph.
    Matches by local name or rdfs:label (case-insensitive) using fast string operations.
    Supports exact match first, then fallback to word-order-independent containment match.
    """
    import re
    t = (term or "").strip().lower()
    if not t:
        return None
        
    t_norm = re.sub(r'[\s_\-]', '', t)

    # Stage 1: Try exact match on any typed class or property first (to prioritize schema elements)
    q1 = f"""
    SELECT DISTINCT ?s WHERE {{
      GRAPH <{graph_iri}> {{
        ?s a ?type .
        FILTER(?type IN (
          <http://www.w3.org/2002/07/owl#Class>, 
          <http://www.w3.org/2000/01/rdf-schema#Class>, 
          <http://www.w3.org/1999/02/22-rdf-syntax-ns#Property>, 
          <http://www.w3.org/2002/07/owl#ObjectProperty>, 
          <http://www.w3.org/2002/07/owl#DatatypeProperty>
        ))
        OPTIONAL {{ ?s <http://www.w3.org/2000/01/rdf-schema#label> ?lbl }}
        FILTER(
          (BOUND(?lbl) && REPLACE(LCASE(STR(?lbl)), "[\\\\s_\\\\-]", "") = "{t_norm}") ||
          STRENDS(REPLACE(LCASE(STR(?s)), "[\\\\s_\\\\-]", ""), "/{t_norm}") || 
          STRENDS(REPLACE(LCASE(STR(?s)), "[\\\\s_\\\\-]", ""), "#{t_norm}")
        )
      }}
    }}
    LIMIT 1
    """
    try:
        rows1 = _exec_select(q1)["results"]["bindings"]
        if rows1:
            return rows1[0]["s"]["value"]
    except Exception:
        pass

    # Stage 2: Try exact match on ANY subject in the graph (implicit classes/properties/instances)
    q2 = f"""
    SELECT DISTINCT ?s WHERE {{
      GRAPH <{graph_iri}> {{
        ?s ?p ?o .
        OPTIONAL {{ ?s <http://www.w3.org/2000/01/rdf-schema#label> ?lbl }}
        FILTER(
          (BOUND(?lbl) && REPLACE(LCASE(STR(?lbl)), "[\\\\s_\\\\-]", "") = "{t_norm}") ||
          STRENDS(REPLACE(LCASE(STR(?s)), "[\\\\s_\\\\-]", ""), "/{t_norm}") || 
          STRENDS(REPLACE(LCASE(STR(?s)), "[\\\\s_\\\\-]", ""), "#{t_norm}")
        )
      }}
      FILTER(isIRI(?s))
    }}
    LIMIT 1
    """
    try:
        rows2 = _exec_select(q2)["results"]["bindings"]
        if rows2:
            return rows2[0]["s"]["value"]
    except Exception:
        pass

    # Stage 3: Word-order-independent containment match
    words = [w.strip().lower() for w in re.split(r'[\s_\-]+', term) if w.strip()]
    if words:
        lbl_filters = " && ".join(f'CONTAINS(LCASE(STR(?lbl)), "{w}")' for w in words)
        iri_filters = " && ".join(f'CONTAINS(LCASE(STR(?s)), "{w}")' for w in words)
        q3 = f"""
        SELECT DISTINCT ?s WHERE {{
          GRAPH <{graph_iri}> {{
            ?s ?p ?o .
            OPTIONAL {{ ?s <http://www.w3.org/2000/01/rdf-schema#label> ?lbl }}
            FILTER(
              (BOUND(?lbl) && {lbl_filters}) ||
              ({iri_filters})
            )
          }}
          FILTER(isIRI(?s))
        }}
        LIMIT 1
        """
        try:
            rows3 = _exec_select(q3)["results"]["bindings"]
            if rows3:
                return rows3[0]["s"]["value"]
        except Exception:
            pass

    return None

def graph_has_triples(graph_iri: str) -> bool:
    """Check if a graph contains any triples."""
    q = f"""
    SELECT ?s WHERE {{
      GRAPH <{graph_iri}> {{ ?s ?p ?o }}
    }} LIMIT 1
    """
    try:
        rows = _exec_select(q)["results"]["bindings"]
        return len(rows) > 0
    except Exception:
        return False



def find_graphs_by_name(name_hint: str) -> List[str]:
    """Find workspace graph IRIs that match the given name hint."""
    t = name_hint.strip().lower()
    
    # Strip common descriptive words that the user/LLM might append
    t = t.replace(" ontology", "").replace(" graph", "").replace(" workspace", "").strip()
    
    if not t:
        return []

    q = PREFIXES + f"""
    SELECT DISTINCT ?g WHERE {{
        GRAPH ?g {{ ?s ?p ?o }}
    }}
    """
    res = _exec_select(q)
    matched = []
    
    t_search = t.replace(" ", "_")
    
    for b in res["results"]["bindings"]:
        g = b["g"]["value"]
        if "workspace" in g.lower() and not g.endswith("/instances") and (t in g.lower() or t_search in g.lower()):
            matched.append(g)
            
    return matched


