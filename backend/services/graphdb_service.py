def build_safe_sparql_query(intent: str, target_graphs: List[str], entity_iri: Optional[str] = None, entity_term: str = "", stat: str = "") -> Optional[str]:
    filter_clause = f"FILTER(?g IN ({','.join([f'<{g}>' for g in target_graphs])}))" if target_graphs else ""
    
    term_lower = entity_term.lower() if entity_term else ""
    
    if intent == "get_numeric_stat" and entity_iri:
        schema_graph = target_graphs[0] if target_graphs else ""
        instance_graph = target_graphs[1] if len(target_graphs) > 1 else schema_graph
        stat_lower = stat.lower() if stat else "all"
        
        if stat_lower == "plot":
            return PREFIXES + f"""
            SELECT ?label ?value WHERE {{
              GRAPH <{schema_graph}> {{
                ?class rdfs:subClassOf* <{entity_iri}> .
              }}
              GRAPH <{instance_graph}> {{
                ?s rdf:type ?class .
                ?s cmpo:hasNumericValue ?value .
                OPTIONAL {{ ?s rdfs:label ?label }}
              }}
            }} LIMIT 100
            """
            
        stat_select = ""
        if stat_lower == "max":
            stat_select = "(MAX(xsd:float(?value)) AS ?max)"
        elif stat_lower == "min":
            stat_select = "(MIN(xsd:float(?value)) AS ?min)"
        elif stat_lower == "avg" or stat_lower == "mean":
            stat_select = "(AVG(xsd:float(?value)) AS ?avg)"
        elif stat_lower == "count":
            stat_select = ""
        else: # all
            stat_select = "(MIN(xsd:float(?value)) AS ?min) (MAX(xsd:float(?value)) AS ?max) (AVG(xsd:float(?value)) AS ?avg)"
            
        return PREFIXES + f"""
        SELECT (COUNT(?s) AS ?count) {stat_select} WHERE {{
          GRAPH <{schema_graph}> {{
            ?class rdfs:subClassOf* <{entity_iri}> .
          }}
          GRAPH <{instance_graph}> {{
            ?s rdf:type ?class .
            ?s cmpo:hasNumericValue ?value .
          }}
        }} LIMIT 1
        """
        
    elif intent == "get_all_classes":
        return PREFIXES + f"""
        SELECT DISTINCT ?class ?label WHERE {{
          GRAPH ?g {{
            {{ ?class a owl:Class }} UNION {{ ?class a <http://www.w3.org/2000/01/rdf-schema#Class> }} UNION {{ ?child rdfs:subClassOf ?class }} UNION {{ ?class rdfs:subClassOf ?parent }}
            OPTIONAL {{ ?class rdfs:label ?label }}
          }}
          {filter_clause}
          FILTER(isIRI(?class))
        }} LIMIT 500
        """
    elif intent == "get_subclasses":
        if entity_iri:
            return PREFIXES + f"""
            SELECT DISTINCT ?subclass ?label WHERE {{
              GRAPH ?g {{
                ?subclass rdfs:subClassOf <{entity_iri}> .
                OPTIONAL {{ ?subclass rdfs:label ?label }}
              }}
              {filter_clause}
              FILTER(isIRI(?subclass))
            }} LIMIT 500
            """
        elif term_lower:
            return PREFIXES + f"""
            SELECT DISTINCT ?subclass ?label WHERE {{
              GRAPH ?g {{
                ?subclass rdfs:subClassOf ?parent .
                OPTIONAL {{ ?subclass rdfs:label ?label }}
                OPTIONAL {{ ?parent rdfs:label ?parentLabel }}
              }}
              {filter_clause}
              FILTER(isIRI(?subclass))
              FILTER(CONTAINS(LCASE(STR(?parent)), "{term_lower}") || (BOUND(?parentLabel) && CONTAINS(LCASE(STR(?parentLabel)), "{term_lower}")))
            }} LIMIT 500
            """
    elif intent == "get_superclasses":
        if entity_iri:
            return PREFIXES + f"""
            SELECT DISTINCT ?superclass ?label WHERE {{
              GRAPH ?g {{
                <{entity_iri}> rdfs:subClassOf ?superclass .
                OPTIONAL {{ ?superclass rdfs:label ?label }}
              }}
              {filter_clause}
              FILTER(isIRI(?superclass))
            }} LIMIT 500
            """
        elif term_lower:
            return PREFIXES + f"""
            SELECT DISTINCT ?superclass ?label WHERE {{
              GRAPH ?g {{
                ?child rdfs:subClassOf ?superclass .
                OPTIONAL {{ ?superclass rdfs:label ?label }}
                OPTIONAL {{ ?child rdfs:label ?childLabel }}
              }}
              {filter_clause}
              FILTER(isIRI(?superclass))
              FILTER(CONTAINS(LCASE(STR(?child)), "{term_lower}") || (BOUND(?childLabel) && CONTAINS(LCASE(STR(?childLabel)), "{term_lower}")))
            }} LIMIT 500
            """
    elif intent == "get_properties":
        return PREFIXES + f"""
        SELECT DISTINCT ?prop ?propType ?label WHERE {{
          GRAPH ?g {{
            ?prop a ?propType .
            FILTER(?propType IN (rdf:Property, owl:ObjectProperty, owl:DatatypeProperty))
            OPTIONAL {{ ?prop rdfs:label ?label }}
          }}
          {filter_clause}
          FILTER(isIRI(?prop))
        }} LIMIT 500
        """
    elif intent == "get_object_properties":
        return PREFIXES + f"""
        SELECT DISTINCT ?prop ?label WHERE {{
          GRAPH ?g {{
            ?prop a owl:ObjectProperty .
            OPTIONAL {{ ?prop rdfs:label ?label }}
          }}
          {filter_clause}
          FILTER(isIRI(?prop))
        }} LIMIT 500
        """
    elif intent == "get_datatype_properties":
        return PREFIXES + f"""
        SELECT DISTINCT ?prop ?label WHERE {{
          GRAPH ?g {{
            ?prop a owl:DatatypeProperty .
            OPTIONAL {{ ?prop rdfs:label ?label }}
          }}
          {filter_clause}
          FILTER(isIRI(?prop))
        }} LIMIT 500
        """
    elif intent == "get_instances":
        if entity_iri:
            return PREFIXES + f"""
            SELECT DISTINCT ?instance ?label WHERE {{
              GRAPH ?g {{
                ?instance a <{entity_iri}> .
                OPTIONAL {{ ?instance rdfs:label ?label }}
              }}
              {filter_clause}
              FILTER(isIRI(?instance))
            }} LIMIT 500
            """
        elif term_lower:
            return PREFIXES + f"""
            SELECT DISTINCT ?instance ?label WHERE {{
              GRAPH ?g {{
                ?instance a ?type .
                OPTIONAL {{ ?instance rdfs:label ?label }}
                OPTIONAL {{ ?type rdfs:label ?typeLabel }}
              }}
              {filter_clause}
              FILTER(isIRI(?instance))
              FILTER(CONTAINS(LCASE(STR(?type)), "{term_lower}") || (BOUND(?typeLabel) && CONTAINS(LCASE(STR(?typeLabel)), "{term_lower}")))
            }} LIMIT 500
            """
        else:
            return PREFIXES + f"""
            SELECT DISTINCT ?instance ?label WHERE {{
              GRAPH ?g {{
                ?instance a ?type .
                OPTIONAL {{ ?instance rdfs:label ?label }}
              }}
              {filter_clause}
              FILTER(isIRI(?instance))
              FILTER(?type NOT IN (owl:Class, <http://www.w3.org/2000/01/rdf-schema#Class>, rdf:Property, owl:ObjectProperty, owl:DatatypeProperty, owl:Ontology))
            }} LIMIT 500
            """
    elif intent == "get_domain_range":
        if entity_iri:
            return PREFIXES + f"""
            SELECT DISTINCT ?domain ?range WHERE {{
              GRAPH ?g {{
                OPTIONAL {{ <{entity_iri}> rdfs:domain ?domain }}
                OPTIONAL {{ <{entity_iri}> rdfs:range ?range }}
              }}
              {filter_clause}
            }} LIMIT 10
            """
        elif term_lower:
            return PREFIXES + f"""
            SELECT DISTINCT ?domain ?range WHERE {{
              GRAPH ?g {{
                ?prop a ?propType .
                FILTER(?propType IN (rdf:Property, owl:ObjectProperty, owl:DatatypeProperty))
                OPTIONAL {{ ?prop rdfs:domain ?domain }}
                OPTIONAL {{ ?prop rdfs:range ?range }}
                OPTIONAL {{ ?prop rdfs:label ?label }}
              }}
              {filter_clause}
              FILTER(CONTAINS(LCASE(STR(?prop)), "{term_lower}") || (BOUND(?label) && CONTAINS(LCASE(STR(?label)), "{term_lower}")))
            }} LIMIT 10
            """
    return None
